const result={unresolved:[{targetRef:'target-1',clauseRef:'clause-1',lens:'source_quality',status:'CONTESTED_BY_RECEIPTS'}]};
const base={targetRef:'target-1',clauseRef:'clause-1',organ:'GUT',status:'COMPLETED',provenance:'synthetic-source-a',triageClassification:'PROVENANCE_COLLISION'};
